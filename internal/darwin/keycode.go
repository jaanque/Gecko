package darwin

// VKToMacKeycode maps standard Windows Virtual-Key codes (VK_*) to macOS Carbon/CGKeyCode values.
// Returns (keycode, true) when mapped.
func VKToMacKeycode(vk uint16) (uint16, bool) {
	table := map[uint16]uint16{
		0x41: 0, 0x53: 1, 0x44: 2, 0x46: 3, 0x48: 4, 0x47: 5, 0x5A: 6, 0x58: 7, 0x43: 8, 0x56: 9,
		0x42: 11, 0x51: 12, 0x57: 13, 0x45: 14, 0x52: 15, 0x59: 16, 0x54: 17,
		0x31: 18, 0x32: 19, 0x33: 20, 0x34: 21, 0x36: 22, 0x35: 23, 0xBB: 24, 0x39: 25, 0x37: 26,
		0xBD: 27, 0x38: 28, 0x30: 29, 0xDD: 30, 0x4F: 31, 0x55: 32, 0xDB: 33, 0x49: 34, 0x50: 35,
		0x0D: 36, 0x4C: 37, 0x4A: 38, 0xDE: 39, 0x4B: 40, 0xBA: 41, 0xDC: 42, 0xBC: 43, 0xBF: 44,
		0x4E: 45, 0x4D: 46, 0xBE: 47, 0x09: 48, 0x20: 49, 0xC0: 50, 0x08: 51, 0x1B: 53,
		0x5B: 55, 0x5C: 54, // Command (LWin / RWin)
		0x10: 56, 0xA0: 56, 0xA1: 60, // Shift
		0x14: 57,                     // CapsLock
		0x12: 58, 0xA4: 58, 0xA5: 61, // Option / Alt
		0x11: 59, 0xA2: 59, 0xA3: 62, // Control
		0x2E: 117, // Forward Delete
		0x24: 115, // Home
		0x23: 119, // End
		0x21: 116, // PageUp
		0x22: 121, // PageDown
		0x25: 123, // Left
		0x27: 124, // Right
		0x28: 125, // Down
		0x26: 126, // Up
		0x70: 122, 0x71: 120, 0x72: 99, 0x73: 118, 0x74: 96, 0x75: 97,
		0x76: 98, 0x77: 100, 0x78: 101, 0x79: 109, 0x7A: 103, 0x7B: 111,
	}
	kc, ok := table[vk]
	return kc, ok
}
